#!/usr/bin/env python3
"""Replace the embedded ELF while retaining BlueBomb v1.5's IOS bootstrap."""
import argparse
import struct
import zlib
from pathlib import Path

MARKER = b"PONYPONY"
MEM1_CAPACITY = 512 * 1024
ELF_IDENT = b"\x7fELF\x01\x02\x01"
ELF_EXEC_PPC = b"\x00\x02\x00\x14"


def pack_stage1(original, elf):
    marker = original.find(MARKER)
    if marker < 0 or marker % 4 or original.count(MARKER) != 1:
        raise ValueError("Expected one aligned payload marker")
    size, checksum = struct.unpack_from(">II", original, marker + len(MARKER))
    compressed = original[marker + 16:]
    if len(compressed) != size or (-sum(compressed) & 0xFFFFFFFF) != checksum:
        raise ValueError("Original payload size or checksum is invalid")
    if not zlib.decompress(compressed).startswith(ELF_IDENT):
        raise ValueError("Original payload is not an ELF")
    if not elf.startswith(ELF_IDENT) or elf[16:20] != ELF_EXEC_PPC:
        raise ValueError("Expected a big-endian PowerPC executable")
    compressed = zlib.compress(elf, level=9)
    compressed += b"\0" * (-len(compressed) % 4)
    payload = original[:marker] + MARKER
    payload += struct.pack(">II", len(compressed), -sum(compressed) & 0xFFFFFFFF)
    payload += compressed
    if len(payload) >= MEM1_CAPACITY:
        raise ValueError("Stage 1 exceeds the Wii MEM1 window")
    return payload


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("original", type=Path)
    parser.add_argument("elf", type=Path)
    parser.add_argument("header", type=Path)
    args = parser.parse_args()
    payload = pack_stage1(args.original.read_bytes(), args.elf.read_bytes())
    rows = [
        "    " + ", ".join(f"0x{byte:02x}" for byte in payload[i:i + 12]) + ","
        for i in range(0, len(payload), 12)
    ]
    args.header.write_text(
        "/* Generated by pack-stage1.py. */\n"
        "static const unsigned char stage1_bin[] = {\n"
        + "\n".join(rows)
        + f"\n}};\nstatic const unsigned int stage1_bin_len = {len(payload)};\n"
    )
    print(f"Stage 1: {len(payload)} bytes")
